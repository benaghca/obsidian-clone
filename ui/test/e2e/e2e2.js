const { chromium } = require('playwright-core');
const fs = require('fs'), path = require('path');
const SP = process.env.SP, VAULT = SP + '/vault', OUT = SP + '/shots';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const assert = (c, m) => { if (!c) { throw new Error('ASSERT: ' + m); } else console.log('  ✓', m); };
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  const errors = []; global.PAGE = page; global.ERRS = errors;
  page.on('pageerror', e => errors.push('pageerror: ' + e.message + '\n' + e.stack));
  page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push('console ' + m.type() + ': ' + m.text()); });
  page.on('dialog', d => d.accept());
  // (Cinder asks with its own dialog now: say yes, as the browser dialog handler did)
  await page.addInitScript(() => new MutationObserver(() => document.querySelector('.confirm [data-c="1"]')?.click()).observe(document, { childList: true, subtree: true }));
  await page.goto('http://127.0.0.1:43199/'); await sleep(700);
  await page.click('[data-cmd=new-drawing]'); await sleep(400);
  const file = () => fs.readdirSync(VAULT).filter(f => f.endsWith('.excalidraw')).map(f => [f, fs.statSync(path.join(VAULT, f)).mtimeMs]).sort((a, b) => b[1] - a[1])[0][0];
  const cur = await page.evaluate(() => S.cur);
  const read = () => JSON.parse(fs.readFileSync(path.join(VAULT, cur), 'utf8'));
  const els = () => page.evaluate(() => CinderDraw.getScene().elements.map(e => ({ id: e.id, type: e.type, x: e.x, y: e.y, w: e.width, h: e.height, angle: e.angle, groupIds: e.groupIds, containerId: e.containerId, points: e.points })));
  const box = await page.locator('#view-drawing canvas').boundingBox();
  const X = x => box.x + 200 + x * 0.85, Y = y => box.y + y;
  // Handle positions from the element box and view (pad 6px; rotation handle 22px above).
  const handlePos = async name => page.evaluate(n => {
    const el = CinderDraw.getScene().elements[0], v = CinderDraw.getView(), r = document.querySelector('.dr-canvas').getBoundingClientRect();
    const s = (x, y) => [r.left + (x + v.sx) * v.zoom, r.top + (y + v.sy) * v.zoom], pad = 6 / v.zoom;
    return n === 'se' ? s(el.x + el.width + pad, el.y + el.height + pad) : s(el.x + el.width / 2, el.y - pad - 22 / v.zoom);
  }, name);
  const drag = async (x1, y1, x2, y2, mods = []) => { for (const m of mods) await page.keyboard.down(m); await page.mouse.move(X(x1), Y(y1)); await page.mouse.down(); await page.mouse.move(X((x1 + x2) / 2), Y((y1 + y2) / 2), { steps: 4 }); await page.mouse.move(X(x2), Y(y2), { steps: 4 }); await page.mouse.up(); for (const m of mods) await page.keyboard.up(m); };
  console.log('shapes');
  await page.keyboard.press('r'); await drag(100, 150, 250, 250);
  await page.keyboard.press('r'); await drag(300, 150, 400, 300, ['Shift']);
  let e = await els();
  console.log(JSON.stringify(e.map(x => [x.type, x.x, x.y, x.w, x.h])));
  assert(e.length === 2 && Math.abs(e[1].w - e[1].h) < 0.01, 'shift draws a square');
  assert(await page.evaluate(() => document.querySelector('.dr-tools .active').dataset.tool) === 'selection', 'tool returns to selection after drawing');
  await page.screenshot({ path: OUT + '/10-selected.png' });
  console.log('resize & rotate');
  // select first rect by clicking its edge, resize from se handle
  await page.mouse.click(X(100), Y(200));
  e = await els();
  const r0 = e[0];
  // se handle is at bottom-right + 6px padding (zoom 1)
  const seH = await handlePos('se');
  await page.mouse.move(seH[0], seH[1]); await page.mouse.down(); await page.mouse.move(seH[0] + 25, seH[1] + 20, { steps: 3 }); await page.mouse.move(seH[0] + 50, seH[1] + 40, { steps: 3 }); await page.mouse.up();
  e = await els();
  assert(Math.abs(e[0].w - (r0.w + 50)) < 1.5 && Math.abs(e[0].h - (r0.h + 40)) < 1.5, `se-resize grows the box (${r0.w}x${r0.h} -> ${e[0].w.toFixed(1)}x${e[0].h.toFixed(1)})`);
  // rotation handle: above top-centre by 22px + 6 pad
  const rot = await handlePos('rotate');
  await page.mouse.move(rot[0], rot[1]); await page.mouse.down(); await page.mouse.move(rot[0] + 40, rot[1] + 5, { steps: 3 }); await page.mouse.move(rot[0] + 80, rot[1] + 10, { steps: 3 }); await page.mouse.up();
  e = await els();
  assert(e[0].angle > 0.1, 'rotation handle rotates (angle ' + e[0].angle.toFixed(2) + ')');
  await page.keyboard.press('Control+z'); await sleep(50);
  e = await els();
  assert(Math.abs(e[0].angle) < 1e-9, 'undo restores angle');
  console.log('marquee, group, copy/paste, delete');
  await page.keyboard.press('Escape');
  await drag(60, 110, 560, 330);
  assert((await page.$$eval('.dr-props h5', h => h.map(x => x.textContent))).includes('Align'), 'marquee selects both (Align shown)');
  await page.keyboard.press('Control+g'); await sleep(50);
  e = await els();
  assert(e[0].groupIds.length === 1 && e[0].groupIds[0] === e[1].groupIds[0], 'grouped');
  await page.keyboard.press('Escape');
  await page.mouse.click(X(100), Y(200));
  await page.keyboard.press('Control+c');
  await page.mouse.move(X(400), Y(500));
  await page.keyboard.press('Control+v'); await sleep(100);
  e = await els();
  assert(e.length === 4, 'copy/paste duplicates the group (' + e.length + ')');
  assert(e[2].groupIds[0] && e[2].groupIds[0] !== e[0].groupIds[0], 'pasted copy gets a new group id');
  await page.keyboard.press('Delete');
  e = await els();
  assert(e.length === 2, 'delete removes pasted group');
  await page.keyboard.press('Control+d'); await sleep(50);
  // selection is original group after delete? nothing selected -> no-op
  console.log('multi-point line, freedraw, eraser');
  await page.keyboard.press('l');
  await page.mouse.click(X(500), Y(420)); await page.mouse.move(X(600), Y(380)); await page.mouse.click(X(600), Y(380));
  await page.mouse.move(X(650), Y(480)); await page.mouse.click(X(650), Y(480));
  await page.keyboard.press('Enter'); await sleep(50);
  e = await els();
  const line = e.find(x => x.type === 'line');
  assert(line && line.points.length === 3, 'click-by-click line has 3 points (' + line?.points.length + ')');
  await page.keyboard.press('p');
  await page.mouse.move(X(120), Y(450)); await page.mouse.down();
  for (let i = 0; i <= 30; i++) await page.mouse.move(X(120 + i * 6), Y(450 + Math.sin(i / 3) * 25));
  await page.mouse.up();
  e = await els();
  const fd = e.find(x => x.type === 'freedraw');
  assert(fd && fd.points.length > 20, 'freedraw recorded points');
  await page.keyboard.press('e');
  await drag(110, 430, 320, 480);
  e = await els();
  assert(!e.find(x => x.type === 'freedraw'), 'eraser removes the stroke');
  await page.keyboard.press('Control+z');
  e = await els();
  assert(e.find(x => x.type === 'freedraw'), 'undo brings it back');
  console.log('styles via panel');
  await page.keyboard.press('v');
  await page.mouse.click(X(100), Y(200)); // selects group (2 rects)
  await page.click('.dr-props [data-prop=strokeColor][data-value="#e03131"]');
  await page.click('.dr-props [data-prop=backgroundColor][data-value="#ffec99"]');
  await page.click('.dr-props [data-prop=fillStyle][data-value=cross-hatch]');
  await page.click('.dr-props [data-prop=roughness][data-value="2"]');
  await page.click('.dr-props [data-prop=strokeStyle][data-value=dashed]');
  const st = await page.evaluate(() => CinderDraw.getScene().elements.filter(e => e.type === 'rectangle').map(e => [e.strokeColor, e.backgroundColor, e.fillStyle, e.roughness, e.strokeStyle].join()));
  assert(st.every(s => s === '#e03131,#ffec99,cross-hatch,2,dashed'), 'panel styles apply to selection: ' + st[0]);
  await page.screenshot({ path: OUT + '/11-styled.png' });
  console.log('context menu & export');
  await page.mouse.click(X(700), Y(600), { button: 'right' });
  await sleep(100);
  const items = await page.$$eval('#menu-root .menu div', d => d.map(x => x.textContent));
  assert(items.includes('Select all') && items.includes('Copy drawing as PNG'), 'canvas context menu: ' + items.join(' | '));
  await page.keyboard.press('Escape'); await page.mouse.click(X(700), Y(650));
  await page.click('.dr-menu [data-act=menu]');
  await page.click('#menu-root .menu div:has-text("Export as SVG")'); await sleep(800);
  await page.click('.dr-menu [data-act=menu]');
  await page.click('#menu-root .menu div:has-text("Export as PNG")'); await sleep(1000);
  const base = cur.replace(/\.excalidraw$/, '');
  const svgPath = path.join(VAULT, base + '.svg'), pngPath = path.join(VAULT, base + '.png');
  assert(fs.existsSync(svgPath) && fs.readFileSync(svgPath, 'utf8').startsWith('<svg'), 'exported SVG into the vault');
  const png = fs.readFileSync(pngPath);
  assert(png.slice(1, 4).toString() === 'PNG' && png.length > 2000, 'exported PNG into the vault (' + png.length + ' bytes)');
  console.log('help, dark mode');
  await page.keyboard.press('?'); await sleep(100);
  assert(await page.isVisible('.dr-help'), 'shortcut help opens');
  await page.screenshot({ path: OUT + '/12-help.png' });
  await page.keyboard.press('Escape'); await sleep(100);
  assert(!(await page.isVisible('.dr-help')), 'help closes on Escape');
  await page.click('[data-cmd=theme]'); await sleep(300);
  await page.mouse.click(X(100), Y(200));
  await page.screenshot({ path: OUT + '/13-dark.png' });
  await page.click('[data-cmd=theme]'); await sleep(200);
  console.log('save + external change');
  await sleep(1200);
  const disk = read();
  assert(disk.elements.length === (await els()).length, 'autosaved to disk (' + disk.elements.length + ' elements)');
  disk.elements.push({ id: 'ext1', type: 'ellipse', x: 600, y: 100, width: 80, height: 80, strokeColor: '#1971c2', backgroundColor: 'transparent', seed: 5 });
  fs.writeFileSync(path.join(VAULT, cur), JSON.stringify(disk));
  await sleep(2600);
  e = await els();
  assert(e.find(x => x.id === 'ext1'), 'picks up external edit');
  console.log('obsidian .excalidraw.md format');
  await page.evaluate(() => openSettings('drawings'));
  await page.selectOption('select[name=drawingFormat]', 'md');
  await page.click('.st [data-x]');
  await page.click('[data-cmd=new-drawing]'); await sleep(500);
  const md = await page.evaluate(() => S.cur);
  assert(/\.excalidraw\.md$/.test(md), 'new drawing uses .excalidraw.md: ' + md);
  await page.keyboard.press('t'); await page.mouse.click(X(200), Y(300)); await page.keyboard.type('Link to [[Welcome]]'); await page.keyboard.press('Escape');
  await page.keyboard.press('r'); await drag(400, 200, 500, 300);
  await sleep(1500);
  const mdText = fs.readFileSync(path.join(VAULT, md), 'utf8');
  assert(mdText.includes('excalidraw-plugin: parsed') && /## Text Elements\nLink to \[\[Welcome\]\] \^\w+\n/.test(mdText) && mdText.includes('## Drawing\n```json\n'), 'md drawing has plugin layout');
  await page.click('.tabs [data-rtab=outgoing]'); await sleep(200);
  assert((await page.textContent('#right-body')).includes('Welcome'), 'md drawing text links show as outgoing links');
  await page.keyboard.press('Control+o'); await page.keyboard.type('Welcome'); await page.keyboard.press('Enter'); await sleep(500);
  await page.click('.tabs [data-rtab=backlinks]'); await sleep(200);
  assert((await page.textContent('#right-body')).includes(path.basename(md, '.md')), 'Welcome shows a backlink from the drawing');
  // ctrl+click link in drawing text follows
  await page.keyboard.press('Alt+ArrowLeft'); await sleep(600);
  assert(await page.evaluate(() => S.view) === 'drawing', 'back returns to drawing');
  await page.keyboard.down('Control'); await page.mouse.click(X(210), Y(300)); await page.keyboard.up('Control'); await sleep(500);
  assert(await page.evaluate(() => S.cur) === 'Welcome.md', 'Ctrl+click on [[link]] text follows it');
  console.log('ERRORS:\n' + (errors.join('\n') || 'none'));
  await browser.close();
})().catch(async e => { console.error(e.message.split('\n')[0]); try { await global.PAGE.screenshot({ path: OUT + '/fail.png' }); } catch {} console.log('ERRORS:\n' + global.ERRS.join('\n')); process.exit(1); });
